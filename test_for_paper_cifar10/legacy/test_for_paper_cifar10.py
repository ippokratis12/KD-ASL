# Define the ResNet-18 encoder
class Encoder32(nn.Module):
    def __init__(self, latent_dim=10):
        super().__init__()
        try: base = torchvision.models.resnet18(weights=None)           # ≥ 0.13
        except TypeError: base = torchvision.models.resnet18(pretrained=False)
        self.features = nn.Sequential(*list(base.children())[:-2])
        self.fc = nn.Linear(512, latent_dim)
    def forward(self, x): return self.fc(self.features(x).flatten(1))

class Decoder32(nn.Module):
    def __init__(self, latent_dim=10):
        super().__init__()
        self.fc = nn.Linear(latent_dim, 512)
        self.deconv = nn.Sequential(
            nn.ConvTranspose2d(512,256,4,2,1), nn.ReLU(True),
            nn.ConvTranspose2d(256,128,4,2,1), nn.ReLU(True),
            nn.ConvTranspose2d(128, 64,4,2,1), nn.ReLU(True),
            nn.ConvTranspose2d( 64, 64,4,2,1), nn.ReLU(True),
            nn.ConvTranspose2d( 64,  3,4,2,1), nn.Sigmoid()
        )
    def forward(self, z): return self.deconv(self.fc(z).view(z.size(0),512,1,1))

class CAE2(nn.Module):
    def __init__(self, latent_dim=10):
        super().__init__()
        self.encoder = Encoder32(latent_dim)
        self.decoder = Decoder32(latent_dim)
    def forward(self, x): z = self.encoder(x); return self.decoder(z), z

class General_Class_Network(nn.Module):
    def __init__(self, input_size=10, output_size=10, noise_std=1e-4):  # Αλλαγή από 100 σε 10
        super().__init__()
        self.linear = nn.Linear(input_size, output_size, bias=False)
