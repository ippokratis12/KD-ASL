# 6b) KD+ASL training loop                                                    #
# --------------------------------------------------------------------------- #
def train_student_kd_asl(
    m, teacher, ae, ae_t, gcn_s, gcn_t,
    tr, te, * ,
    device, epochs,
    T_kd, alpha_kd,
    alpha_gcn, beta_ae, T_ae,
    lam_rec=2.,
    alpha_gcn_t=0.1, beta_ae_t=0.1, T_ae_t=5.0
):
    """
    KD+ASL training loop που ακολουθεί τα eq. (3.11)–(3.19).
    """

    # -------------------------------------------------------------- #
    #  Βοηθητικές συναρτήσεις
    # -------------------------------------------------------------- #
    def kd_kl_from_probs(s_logits, t_probs, *, T):
        # t_probs: probabilities (soft targets)
        t_probs = t_probs.detach()

        return F.kl_div(
            F.log_softmax(s_logits / T, dim=1),
            t_probs,
            reduction="batchmean"
        ) * (T * T)

    crit_ce      = nn.CrossEntropyLoss()     # CE(s(z), argmax y)
    crit_bce_log = nn.BCEWithLogitsLoss()   # BCE_logits(ŷ_s, ŷ)
    crit_bce     = nn.BCELoss()             # BCE(ŷ̃_gcn-*, s(f_s(x))^†)
    crit_mse     = nn.MSELoss()

    # SGD για student με Cosine Annealing
    opt = _sgd_optimizer(m.parameters(), lr=0.1)
    scheduler = CosineAnnealingLR(opt, T_max=epochs)

    # Adam για AE & GCN branches (πιο επιθετικό LR για καλύτερο ζ)
    gopt_s   = optim.Adam(gcn_s.parameters(),  lr=1e-5)
    gopt_t   = optim.Adam(gcn_t.parameters(),  lr=1e-5)
    gsch_s = CosineAnnealingLR(gopt_s, T_max=epochs)
    gsch_t = CosineAnnealingLR(gopt_t, T_max=epochs)
    opt_ae = optim.Adam(ae.parameters(), lr=1e-5)
    opt_ae_t = optim.Adam(ae_t.parameters(), lr=1e-5)
    ae_sch = CosineAnnealingLR(opt_ae, T_max=epochs)
    ae_t_sch = CosineAnnealingLR(opt_ae_t, T_max=epochs)

    # -------------------------------------------------------------- #
    #  Modes / device setup
    # -------------------------------------------------------------- #
    m.to(device)
    teacher.eval().to(device)
    ae.train().to(device)
    ae_t.train().to(device)
    gcn_s.train().to(device)
    gcn_t.train().to(device)

    for p in teacher.parameters():
        p.requires_grad = False  # teacher ensemble frozen

    # -------------------------------------------------------------- #
    #  Training loop
    # -------------------------------------------------------------- #
    for ep in range(epochs):
        m.train()
        loss = cor = tot = 0
        sum_y_hat = sum_y_hat_t = 0.0
        sum_ae_s = sum_ae_t = 0.0
        sum_teacher = sum_student = 0.0
        total_samples = 0

        for images, labels in tr:
            x, y = images.to(device), labels.to(device)
            labels_idx = y
            C = m.fc.out_features
            y_onehot = F.one_hot(y, num_classes=C).float()

            # Zero grads
            opt.zero_grad()
            opt_ae.zero_grad()
            opt_ae_t.zero_grad()
            gopt_s.zero_grad()
            gopt_t.zero_grad()

            # ---------------- TEACHER / STUDENT forward ---------------- #
            t_logits = teacher(x)                 # f_t(x) = t
            y_t = F.softmax(t_logits / T_kd, dim=1)      # y_t = s(t)
            s_logits = m(x)                       # ŷ_s = f_s(x)

            # ------------------- Student AE & ASL (3.11–3.13) ----------- #
            z = ae.encoder(x)                     # z = h(x)
            x_rec = ae.decoder(z)
            p_ae = F.softmax(z / T_ae, dim=1)     # s(z / T_ae)

            # g_s(y): GCN_s πάνω στο label vector
            gcn_s_logits = gcn_s(y_onehot)
            g_s_y = F.softmax(gcn_s_logits, dim=1)


            # (3.11)  Student-side ASL targets
            y_hat = (
                alpha_gcn * g_s_y +
                beta_ae   * p_ae +
                (1.0 - alpha_gcn - beta_ae) * y_onehot
            )

            # (3.13)  GCN stabilisation target για student GCN
            y_hat_gcn = (
                alpha_gcn * g_s_y +
                beta_ae   * p_ae.detach() +
                (1.0 - alpha_gcn - beta_ae) * y_onehot
            )


            p_student = F.log_softmax(s_logits, dim=1)

            loss_cls = -(y_hat.detach() * p_student).sum(dim=1).mean()

            loss_ae_s = (
                crit_ce(z, labels_idx)
                + lam_rec * crit_mse(x_rec, x)
            )

            # (3.13)  L_gcn-s
            loss_gcn_s = crit_bce(y_hat_gcn, F.softmax(s_logits, dim=1).detach())

            # ------------------- Teacher AE & ASL (3.14–3.18) ----------- #
            z_t = ae_t.encoder(x)                  # z_t = h_t(x)
            x_rec_t = ae_t.decoder(z_t)
            p_ae_t = F.softmax(z_t / T_ae_t, dim=1)

            gcn_t_logits = gcn_t(y_t)
            g_t_yt = F.softmax(gcn_t_logits, dim=1)

            # (3.14) teacher-side ASL targets
            y_hat_t = (
                alpha_gcn_t * g_t_yt +
                beta_ae_t   * p_ae_t +
                (1.0 - alpha_gcn_t - beta_ae_t) * y_t
            )

            # (3.18) teacher GCN stabilisation target
            y_hat_gcn_t = (
                alpha_gcn_t * g_t_yt +
                beta_ae_t   * p_ae_t.detach() +
                (1.0 - alpha_gcn_t - beta_ae_t) * y_t
            )

            loss_gcn_t = crit_bce(y_hat_gcn_t, F.softmax(s_logits, dim=1).detach())

            # ------------------- Distillation block (3.15, 3.17) -------- #
            # Για student distillation (3.15): χρησιμοποιούμε τα y_hat_t ως soft targets
            kd_student = kd_kl_from_probs(s_logits, y_hat_t, T=T_kd)  # KL only (distill)

            # Για teacher AE distillation (3.17): χρησιμοποιούμε τα teacher logits
            kd_teacher_ae = kd_loss(z_t, t_logits, T=T_kd, alpha=alpha_kd)

            loss_distill = kd_student
            loss_ae_t = kd_teacher_ae + lam_rec * crit_mse(x_rec_t, x)
            #     (
            #     alpha_kd * kd_student +
            #     kd_teacher_ae +
            #     lam_rec * crit_mse(x_rec_t, x)
            # ))

            # ------------------------ TOTAL LOSS (3.19) ----------------- #
            total_loss = alpha_kd * loss_cls + (1 - alpha_kd) * loss_distill + loss_ae_t + loss_gcn_s + loss_gcn_t + loss_ae_s
            total_loss.backward()

            opt.step()
            gopt_s.step()
            gopt_t.step()
            opt_ae.step()
            opt_ae_t.step()

            # -------------------- Metrics logging ------------------------ #
            with torch.no_grad():
                # ΜΕΣΟΣ ΟΡΟΣ ΤΟΥ MAX (average confidence), ΟΧΙ p(correct_label)
                max_y_hat, _     = y_hat.max(dim=1)
                max_y_hat_t, _   = y_hat_t.max(dim=1)
                max_ae_s, _      = p_ae.max(dim=1)
                max_ae_t, _      = p_ae_t.max(dim=1)
                max_teacher, _   = y_t.max(dim=1)
                max_student, _   = F.softmax(s_logits, dim=1).max(dim=1)

                sum_y_hat     += max_y_hat.sum().item()
                sum_y_hat_t   += max_y_hat_t.sum().item()
                sum_ae_s      += max_ae_s.sum().item()
                sum_ae_t      += max_ae_t.sum().item()
                sum_teacher   += max_teacher.sum().item()
                sum_student   += max_student.sum().item()
                total_samples += y.size(0)

            loss += total_loss.item() * x.size(0)
            cor  += s_logits.argmax(1).eq(labels_idx).sum().item()
            tot  += labels_idx.size(0)

        scheduler.step()
        gsch_s.step()  # gcn_s LR update (per-epoch)
        gsch_t.step()  # gcn_t LR update (per-epoch)
        ae_sch.step()
        ae_t_sch.step()

        tr_l, tr_a = loss / tot, 100. * cor / tot
        vl_l, vl_a = validate(m, te, crit_ce, device)

        mean_y_hat     = sum_y_hat     / total_samples
        mean_y_hat_t   = sum_y_hat_t   / total_samples
        mean_ae_s      = sum_ae_s      / total_samples
        mean_ae_t      = sum_ae_t      / total_samples
        mean_teacher   = sum_teacher   / total_samples
        mean_student   = sum_student   / total_samples

        print(
            f"[KD+ASL] Ep {ep+1:02}/{epochs} | "
            f"Train {tr_l:.4f}/{tr_a:.2f}% | "
            f"Val {vl_l:.4f}/{vl_a:.2f}% | "
            f"LR {scheduler.get_last_lr()[0]:.6f} | "
            f"soft(y_hat)={mean_y_hat:.3f}, "
            f"soft(y_hat_t)={mean_y_hat_t:.3f}, "
            f"soft(AE_s)={mean_ae_s:.3f}, "
            f"soft(AE_t)={mean_ae_t:.3f}, "
            f"soft(teacher)={mean_teacher:.3f}, "
            f"soft(student)={mean_student:.3f}"
        )

    return m


