class ResNet18Backbone(nn.Module):
    def __init__(self, n_classes=10):  # Αλλαγή από 100 σε 10 κλάσεις
        super().__init__()
        try:
            base = torchvision.models.resnet18(weights=None)
        except TypeError:
            base = torchvision.models.resnet18(pretrained=False)

        # Modify first conv for CIFAR (32x32 images)
        base.conv1 = nn.Conv2d(3, 64, kernel_size=3, stride=1, padding=1, bias=False)
        base.maxpool = nn.Identity()  # Remove initial maxpool

        self.features = nn.Sequential(*list(base.children())[:-1])
        in_feats = base.fc.in_features
        self.fc = nn.Linear(in_feats, n_classes)

    def forward(self, x):
        x = self.features(x).flatten(1)
        return self.fc(x)

    def get_features(self, x):
        x = self.features(x).flatten(1)
        return x

def resnet18_backbone(n_classes=10):  # Αλλαγή από 100 σε 10 κλάσεις
    return ResNet18Backbone(n_classes=n_classes)

